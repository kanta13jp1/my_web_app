String? _pendingHomeToolRoutePath;

// route -> 表示名 の遅延キャッシュ。カタログ全エントリの起動記録でラベル解決に使う。
Map<String, String>? _routeTitleCache;
Map<String, String> _routeTitleMap() {
  return _routeTitleCache ??= <String, String>{
    for (final entry in buildHomeToolCatalog())
      if (entry.routePath != null && entry.routePath!.isNotEmpty)
        entry.routePath!: entry.title,
  };
}

HomeToolOpenCallback _wrapRouteAwareHomeToolOpen(
  HomeToolOpenCallback onOpen,
  String? routePath,
) {
  return (context) async {
    final canonicalRoutePath =
        routePath == null ? null : canonicalFeatureRoutePath(routePath);
    final previous = _pendingHomeToolRoutePath;
    _pendingHomeToolRoutePath = canonicalRoutePath;
    // ホームの「最近使った機能 / よく使われる機能」は user_feature_usage を参照する。
    // 業務メニュー・ホームタイルなどカタログ経由の全機能起動はこのラッパーを通るため、
    // ここで DB へ記録する (個別の起動口での記録漏れを一掃する単一チョークポイント)。
    if (canonicalRoutePath != null && canonicalRoutePath.isNotEmpty) {
      final label = _routeTitleMap()[canonicalRoutePath] ??
          featureLabelForRoute(canonicalRoutePath);
      unawaited(recordFeatureTap(canonicalRoutePath, label));
    }
    try {
      await onOpen(context);
    } finally {
      _pendingHomeToolRoutePath = previous;
    }
  };
}

Future<void> _pushPage(BuildContext context, Widget page) {
  final routePath = _pendingHomeToolRoutePath;
  _pendingHomeToolRoutePath = null;
  return Navigator.of(context).push(
    MaterialPageRoute(
      settings: routePath == null ? null : RouteSettings(name: routePath),
      builder: (_) => page,
    ),
  );
}

String? _homeToolRoutePathForId(String id) {
  switch (id) {
    case 'digital-danshari':
      return '/digital-danshari';
    case 'agent-org':
      return '/agents';
    case 'admin-analytics':
      return '/admin';
    case 'edge-function-status':
      return '/edge-functions';
    case 'public-profile':
      return null;
    default:
      return '/$id';
  }
}

