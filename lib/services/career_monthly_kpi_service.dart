class CareerMonthlyClosingSnapshot {
  final String monthKey;
  final DateTime generatedAt;
  final String primaryGoal;
  final int completedMetrics;
  final int totalMetrics;
  final int averageProgressPercent;
  final String markdownReport;
  final String checksum;
  final bool autoGenerated;

  const CareerMonthlyClosingSnapshot({
    required this.monthKey,
    required this.generatedAt,
    required this.primaryGoal,
    required this.completedMetrics,
    required this.totalMetrics,
    required this.averageProgressPercent,
    required this.markdownReport,
    required this.checksum,
    this.autoGenerated = false,
  });

  Map<String, dynamic> toJson() {
    return <String, dynamic>{
      'month_key': monthKey,
      'generated_at': generatedAt.toIso8601String(),
      'primary_goal': primaryGoal,
      'completed_metrics': completedMetrics,
      'total_metrics': totalMetrics,
      'average_progress_percent': averageProgressPercent,
      'markdown_report': markdownReport,
      'checksum': checksum,
      'auto_generated': autoGenerated,
    };
  }

  factory CareerMonthlyClosingSnapshot.fromJson(Map<String, dynamic> json) {
    final generated =
        DateTime.tryParse(json['generated_at']?.toString() ?? '') ??
            DateTime.now();
    return CareerMonthlyClosingSnapshot(
      monthKey: json['month_key']?.toString() ?? '',
      generatedAt: generated,
      primaryGoal: json['primary_goal']?.toString() ?? '',
      completedMetrics: (json['completed_metrics'] as num?)?.toInt() ?? 0,
      totalMetrics: (json['total_metrics'] as num?)?.toInt() ?? 0,
      averageProgressPercent:
          (json['average_progress_percent'] as num?)?.toInt() ?? 0,
      markdownReport: json['markdown_report']?.toString() ?? '',
      checksum: json['checksum']?.toString() ?? '',
      autoGenerated: json['auto_generated'] == true,
    );
  }
}

class CareerMonthlyKpiSummary {
  final String monthKey;
  final int totalMetrics;
  final int completedMetrics;
  final double averageProgress;
  final String primaryGoal;

  const CareerMonthlyKpiSummary({
    required this.monthKey,
    required this.totalMetrics,
    required this.completedMetrics,
    required this.averageProgress,
    required this.primaryGoal,
  });
}

class CareerMonthlyKpiService {
  static const String closingSnapshotsPrefsKey =
      'career_kpi_closing_snapshots_v1';

  final SupabaseClient? _client;

  CareerMonthlyKpiService({SupabaseClient? client}) : _client = client;

  SupabaseClient _requireClient() => _client ?? Supabase.instance.client;

  Future<List<CareerMonthlyKpi>> list() async {
    final response = await _requireClient().functions.invoke(
      'tools-hub',
      body: {'action': 'career_kpi.list'},
    );
    final data = response.data;
    final items = data is Map && data['items'] is List
        ? data['items'] as List
        : const <Object?>[];
    final kpis = items
        .whereType<Map>()
        .map(
          (item) =>
              CareerMonthlyKpi.fromHubItem(Map<String, dynamic>.from(item)),
        )
        .toList();
    kpis.sort((a, b) => b.monthKey.compareTo(a.monthKey));
    return kpis;
  }

  Future<CareerMonthlyKpi?> add(CareerMonthlyKpi kpi) async {
    final response = await _requireClient().functions.invoke(
      'tools-hub',
      body: {'action': 'career_kpi.add', ...kpi.toPayload()},
    );
    final data = response.data;
    if (data is Map && data['item'] is Map) {
      return CareerMonthlyKpi.fromHubItem(
        Map<String, dynamic>.from(data['item'] as Map),
      );
    }
    return null;
  }

  Future<void> update(CareerMonthlyKpi kpi) async {
    final id = kpi.id;
    if (id == null || id.isEmpty) {
      throw ArgumentError('A KPI id is required to update an existing record.');
    }
    await _requireClient().functions.invoke(
      'tools-hub',
      body: {'action': 'career_kpi.update', 'id': id, ...kpi.toPayload()},
    );
  }

  Future<void> delete(String id) async {
    await _requireClient().functions.invoke(
      'tools-hub',
      body: {'action': 'career_kpi.delete', 'id': id},
    );
  }

  static CareerMonthlyKpiSummary summarize(
    List<CareerMonthlyKpi> items,
    String monthKey,
  ) {
    final monthlyItems =
        items.where((item) => item.monthKey == monthKey).toList();
    if (monthlyItems.isEmpty) {
      return CareerMonthlyKpiSummary(
        monthKey: monthKey,
        totalMetrics: 0,
        completedMetrics: 0,
        averageProgress: 0,
        primaryGoal: '',
      );
    }
    final completed = monthlyItems
        .where(
          (item) =>
              item.targetValue > 0 && item.actualValue >= item.targetValue,
        )
        .length;
    final progress = monthlyItems
            .map((item) => item.cappedProgress)
            .fold<double>(0, (sum, value) => sum + value) /
        monthlyItems.length;
    final goal = monthlyItems
        .map((item) => item.annualGoal)
        .firstWhere((goal) => goal.trim().isNotEmpty, orElse: () => '');

    return CareerMonthlyKpiSummary(
      monthKey: monthKey,
      totalMetrics: monthlyItems.length,
      completedMetrics: completed,
      averageProgress: progress,
      primaryGoal: goal,
    );
  }

  static String buildMonthlyReport(
    List<CareerMonthlyKpi> items,
    String monthKey,
  ) {
    final monthlyItems =
        items.where((item) => item.monthKey == monthKey).toList();
    final summary = summarize(items, monthKey);
    final buffer = StringBuffer()
      ..writeln('# Career Monthly Close: $monthKey')
      ..writeln()
      ..writeln(
        '- Annual goal: ${summary.primaryGoal.isEmpty ? 'TBD' : summary.primaryGoal}',
      )
      ..writeln(
        '- Metrics: ${summary.completedMetrics}/${summary.totalMetrics} complete',
      )
      ..writeln(
        '- Average progress: ${(summary.averageProgress * 100).round()}%',
      )
      ..writeln();

    if (monthlyItems.isEmpty) {
      buffer
        ..writeln('## KPI Review')
        ..writeln('- No monthly KPI records yet.')
        ..writeln()
        ..writeln('## Next Month Focus')
        ..writeln(
          '- Define one measurable career KPI before the first weekly review.',
        );
      return buffer.toString().trim();
    }

    buffer.writeln('## KPI Review');
    for (final item in monthlyItems) {
      final unit = item.unit.isEmpty ? '' : item.unit;
      buffer
        ..writeln(
          '- ${item.metricName}: ${_formatNumber(item.actualValue)}$unit / '
          '${_formatNumber(item.targetValue)}$unit (${item.achievementPercentLabel})',
        )
        ..writeln(
          '  - Reflection: ${item.reflection.isEmpty ? 'TBD' : item.reflection}',
        )
        ..writeln(
          '  - Next action: ${item.nextAction.isEmpty ? 'TBD' : item.nextAction}',
        );
    }
    return buffer.toString().trim();
  }

  static String computeReportChecksum(String markdown) {
    return sha256.convert(utf8.encode(markdown)).toString().substring(0, 16);
  }

  static CareerMonthlyClosingSnapshot buildClosingSnapshot(
    List<CareerMonthlyKpi> items,
    String monthKey, {
    DateTime? generatedAt,
    bool autoGenerated = false,
  }) {
    final summary = summarize(items, monthKey);
    final markdown = buildMonthlyReport(items, monthKey);
    return CareerMonthlyClosingSnapshot(
      monthKey: monthKey,
      generatedAt: generatedAt ?? DateTime.now(),
      primaryGoal: summary.primaryGoal,
      completedMetrics: summary.completedMetrics,
      totalMetrics: summary.totalMetrics,
      averageProgressPercent: (summary.averageProgress * 100).round(),
      markdownReport: markdown,
      checksum: computeReportChecksum(markdown),
      autoGenerated: autoGenerated,
    );
  }

  Future<List<CareerMonthlyClosingSnapshot>> loadClosingSnapshots() async {
    final prefs = await SharedPreferences.getInstance();
    final raw = prefs.getString(closingSnapshotsPrefsKey);
    if (raw == null || raw.trim().isEmpty) {
      return const <CareerMonthlyClosingSnapshot>[];
    }
    try {
      final decoded = jsonDecode(raw);
      if (decoded is! List) {
        return const <CareerMonthlyClosingSnapshot>[];
      }
      final snapshots = decoded
          .whereType<Map>()
          .map(
            (item) => CareerMonthlyClosingSnapshot.fromJson(
              Map<String, dynamic>.from(item),
            ),
          )
          .toList();
      snapshots.sort((a, b) => b.monthKey.compareTo(a.monthKey));
      return snapshots;
    } catch (_) {
      return const <CareerMonthlyClosingSnapshot>[];
    }
  }

  Future<void> saveClosingSnapshot(
    CareerMonthlyClosingSnapshot snapshot,
  ) async {
    final existing = await loadClosingSnapshots();
    final byMonth = <String, CareerMonthlyClosingSnapshot>{
      for (final item in existing) item.monthKey: item,
    };
    byMonth[snapshot.monthKey] = snapshot;
    final next = byMonth.values.toList()
      ..sort((a, b) => b.monthKey.compareTo(a.monthKey));
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(
      closingSnapshotsPrefsKey,
      jsonEncode(next.take(24).map((item) => item.toJson()).toList()),
    );
  }

  Future<List<CareerMonthlyClosingSnapshot>> ensureMonthEndAutoSnapshot(
    List<CareerMonthlyKpi> items, {
    DateTime? now,
  }) async {
    final reference = now ?? DateTime.now();
    final lastDayOfMonth = DateTime(reference.year, reference.month + 1, 0).day;
    final existing = await loadClosingSnapshots();
    final knownMonths = existing.map((item) => item.monthKey).toSet();

    // Auto-close the current month during the final 2 calendar days, or close
    // the previous month once a new month begins if not yet finalized.
    final String? candidateMonth;
    if (reference.day >= lastDayOfMonth - 1) {
      candidateMonth = CareerMonthlyKpi.currentMonthKey(now: reference);
    } else {
      final prevMonth = DateTime(reference.year, reference.month - 1, 1);
      final prevKey = CareerMonthlyKpi.currentMonthKey(now: prevMonth);
      candidateMonth =
          items.any((item) => item.monthKey == prevKey) ? prevKey : null;
    }

    if (candidateMonth != null && !knownMonths.contains(candidateMonth)) {
      final snapshot = buildClosingSnapshot(
        items,
        candidateMonth,
        generatedAt: reference,
        autoGenerated: true,
      );
      await saveClosingSnapshot(snapshot);
      return loadClosingSnapshots();
    }
    return existing;
  }

  static String _formatNumber(double value) {
    if (value == value.roundToDouble()) {
      return value.round().toString();
    }
    return value.toStringAsFixed(1);
  }
}
