export function checkOutput(actual, expected) {
  if (actual.replace(/\r\n/g, '\n') !== expected) {
    throw new Error('Stale API reference. Run node scripts/api-docs/generate.mjs --write');
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const mode = process.argv[2];
  if (!['--write', '--check'].includes(mode)) throw new Error('Use --write or --check');
  const generated = renderReference(parseDoclets(), readFileSync(path.join(root, sourcePath), 'utf8'));
  if (mode === '--write') writeFileSync(path.join(root, outputPath), generated);
  else checkOutput(readFileSync(path.join(root, outputPath), 'utf8'), generated);
  console.log(`${mode}: ${outputPath}`);
}
