import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

export const root = fileURLToPath(new URL('../../', import.meta.url));
export const sourcePath = 'web/labs/shared/download-json.mjs';
export const outputPath = 'web/labs/shared/reference.html';
const escape = (text) => String(text).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);

export function parseDoclets(source = path.join(root, sourcePath)) {
  // JSDoc parses source only; never import/execute the target module here.
  return JSON.parse(execFileSync(process.execPath, [
    fileURLToPath(new URL('node_modules/jsdoc/jsdoc.js', import.meta.url)),
    '-X', '--pedantic', '-c', fileURLToPath(new URL('jsdoc.json', import.meta.url)), source,
  ], { encoding: 'utf8', maxBuffer: 4 * 1024 * 1024 }));
}

export function documentedFunction(doclets) {
  const matches = doclets.filter((d) => d.kind === 'function' && d.name === 'downloadJson');
  if (matches.length !== 1) throw new Error('Expected exactly one downloadJson function');
  const doc = matches[0];
  const params = doc.params || [];
  if (!doc.description?.trim() || doc.undocumented || !doc.examples?.length ||
      !doc.returns?.[0]?.description?.trim() || !doc.exceptions?.[0]?.description?.trim()) {
    throw new Error('Missing description, example, return or exception documentation');
  }
  const actualParams = doc.meta?.code?.paramnames;
  if (!actualParams || JSON.stringify(params.map((p) => p.name)) !== JSON.stringify(actualParams) ||
      params.some((p) => !p.description?.trim() || !p.type?.names?.length)) {
    throw new Error('Parameter documentation does not match source signature');
  }
  return doc;
}

