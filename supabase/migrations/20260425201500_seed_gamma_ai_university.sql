## 主要機能

### AI スライド生成
- トピックや箇条書きを入力 → 10秒でデザイン済みスライドを生成
- テーマ・フォント・カラーを AI が自動選択
- 1クリックで全スライドをリデザイン

### カード型ドキュメント
- スライドとドキュメントの中間 "Card" 形式
- 折りたたみ可能なネストコンテンツ
- 数式・コードブロック・動画の埋め込みに対応

### Web 公開 & 分析
- URL を共有するだけでリアルタイム表示
- 閲覧者ごとの滞在時間・スライド離脱率を追跡
- パスワード保護・ドメイン制限も可能

### ブランドキット
- 企業ロゴ・カラー・フォントを登録してブランド一貫性を維持
- テンプレートを組織全体で共有

