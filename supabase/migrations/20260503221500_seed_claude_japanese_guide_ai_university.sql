  $$## Claude で日本語開発するとは

**Claude** は日本語を高品質で処理できる数少ないLLMの一つ。英語と同等レベルの**日本語理解・生成**が可能だが、日本語ならではの**文字コード・敬語・文体**への配慮が必要。

## 日本語プロンプト設計の鉄則

```
[文字コード注意事項]
  ・Windows環境: PYTHONUTF8=1 を設定 (CP932エラー回避)
  ・CLIツール: --encoding=utf-8 オプションを付ける
  ・ファイル出力: UTF-8 BOMなしで保存
  ・PowerShell: Out-File -Encoding utf8 を使用

[日本語コンテンツ生成のベストプラクティス]
  ・文体指定: 「です・ます体」か「だ・である体」を明示
  ・敬語レベル: 「丁寧語」「尊敬語」「謙譲語」を指定
  ・文字数制限: 「〇〇字以内」を明示 (日本語は英語の約2倍の情報密度)
  ・句読点: 「、」「。」を使うか、「,」「.」かを指定

[技術用語のローカライズ]
  ・カタカナ vs 日本語訳: 「コンポーネント」vs「部品」
  ・略語: LLM → 大規模言語モデル or LLM
  ・日本語らしさ: 「〜を行う」より「〜する」の方が自然
```

