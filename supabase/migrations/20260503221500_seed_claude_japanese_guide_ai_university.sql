## 日本語コンテンツの品質チェックリスト

| チェック項目 | 確認方法 |
|-----------|---------|
| 送り仮名 | 「行なう」→「行う」/ 「書く」→ OK |
| 助詞の重複 | 「について」「に関して」の連続を避ける |
| 二重否定 | 「〜でないことはない」→ 「〜である」 |
| 外来語統一 | 同じ概念に「コンポーネント」と「コンポ」が混在しない |
| 文末統一 | 「〜です」と「〜だ」が混在しない |

