-- SYNTHETIC TEST ONLY. Never run against a live or shared database.
-- Separate from the RLS fixture. Never connect to a real or shared DB.
-- The guard is not proof of isolation. Roles and schemas survive rollback;
-- independently reviewed disposable-cluster teardown remains necessary.
\set ON_ERROR_STOP on

DO $guard$
BEGIN
  IF pg_catalog.current_database() <> 'salary_identity_isolated'
     OR pg_catalog.current_setting('salary_test.isolated', true)
          IS DISTINCT FROM 'disposable-pg17-only'
     OR pg_catalog.current_setting('server_version_num')::integer < 170000
     OR pg_catalog.current_setting('server_version_num')::integer >= 180000
     OR (pg_catalog.inet_server_addr() IS NOT NULL
         AND pg_catalog.inet_server_addr() NOT IN
           ('127.0.0.1'::inet, '::1'::inet))
     OR pg_catalog.to_regnamespace('auth') IS NOT NULL
     OR pg_catalog.to_regclass('public.cfo_assets') IS NOT NULL
     OR pg_catalog.to_regclass('public.asset_balance_accounts') IS NOT NULL
     OR EXISTS (SELECT 1 FROM pg_catalog.pg_roles
                WHERE rolname IN ('anon', 'authenticated')) THEN
    RAISE EXCEPTION 'unsafe or non-empty fixture: use a disposable PostgreSQL 17 cluster';
  END IF;
END
$guard$;

-- Additional safety checks before any fixture write. This setup models no
-- production authentication: auth.jwt() is a constant synthetic service role.
DO $fixture_guard$
BEGIN
  IF pg_catalog.to_regclass('public.account_deletion_direct_delete_adapters') IS NOT NULL
     OR pg_catalog.to_regclass('public.deletion_rollback_probe') IS NOT NULL
     OR pg_catalog.to_regclass('public.deletion_probe_audit_seq') IS NOT NULL
     OR pg_catalog.to_regprocedure('public.account_deletion_dependency_inventory(uuid)') IS NOT NULL
     OR pg_catalog.to_regprocedure('public.delete_account_deletion_direct_rows(uuid)') IS NOT NULL THEN
    RAISE EXCEPTION 'unexpected existing deletion fixture objects';
  END IF;
END
$fixture_guard$;

CREATE SCHEMA auth;
CREATE TABLE auth.users (id uuid PRIMARY KEY);
CREATE FUNCTION auth.jwt() RETURNS jsonb LANGUAGE sql STABLE SET search_path = ''
AS $jwt$ SELECT '{"role":"service_role"}'::jsonb $jwt$;

-- Fixture data model: both owner FKs initially NO ACTION. It is not a claim
-- about the live cfo_assets FK; case C separately models auth CASCADE.
CREATE TABLE public.account_deletion_direct_delete_adapters (
  schema_name text NOT NULL DEFAULT 'public' CHECK (schema_name = 'public'),
  table_name text NOT NULL,
  column_name text NOT NULL DEFAULT 'user_id' CHECK (column_name = 'user_id'),
  PRIMARY KEY (schema_name, table_name, column_name)
);
CREATE TABLE public.asset_balance_accounts (
  id uuid PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id),
  display_name text NOT NULL,
  UNIQUE (user_id, id)
);
CREATE TABLE public.cfo_assets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL,
  title text NOT NULL,
  amount numeric NOT NULL,
  balance_account_id uuid,
  CONSTRAINT synthetic_cfo_owner_fk FOREIGN KEY (user_id) REFERENCES auth.users(id),
  CONSTRAINT synthetic_cfo_account_fk FOREIGN KEY (user_id, balance_account_id)
    REFERENCES public.asset_balance_accounts(user_id, id)
);
CREATE TABLE public.deletion_rollback_probe (
  id integer PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id)
);
-- A synthetic sequence records the AFTER DELETE event even if the surrounding
-- savepoint rolls back. It is not financial data and requires cluster teardown.
CREATE SEQUENCE public.deletion_probe_audit_seq;
CREATE FUNCTION public.fixture_probe_after_delete()
RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $probe$
BEGIN
  IF OLD.id = 1 AND OLD.user_id = '11111111-1111-4111-8111-111111111111' THEN
    PERFORM pg_catalog.nextval('public.deletion_probe_audit_seq'::regclass);
  END IF;
  RETURN OLD;
END
$probe$;
CREATE TRIGGER fixture_probe_after_delete
AFTER DELETE ON public.deletion_rollback_probe
FOR EACH ROW EXECUTE FUNCTION public.fixture_probe_after_delete();

