-- Only the synthetic target version is rejected. This does not simulate an
-- interrupted connection, a lost COMMIT acknowledgement, or real JWT/RLS.
CREATE FUNCTION supabase_migrations.fixture_reject_target_version()
RETURNS trigger LANGUAGE plpgsql SET search_path = ''
AS $reject$
BEGIN
  IF NEW.version = '20261104000001' THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001',
      MESSAGE = 'synthetic_history_insert_rejected_20261104000001';
  END IF;
  RETURN NEW;
END
$reject$;
CREATE TRIGGER fixture_reject_target_version
BEFORE INSERT ON supabase_migrations.schema_migrations
FOR EACH ROW EXECUTE FUNCTION supabase_migrations.fixture_reject_target_version();

