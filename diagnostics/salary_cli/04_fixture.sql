-- Match the observed cfo_assets policies and table grants, not the full
-- Supabase role graph. The fake roles have no login, inheritance or BYPASSRLS.
CREATE ROLE anon NOLOGIN NOINHERIT NOBYPASSRLS;
CREATE ROLE authenticated NOLOGIN NOINHERIT NOBYPASSRLS;
CREATE SCHEMA auth;
CREATE TABLE auth.users (id uuid PRIMARY KEY);
CREATE FUNCTION auth.uid() RETURNS uuid
LANGUAGE sql STABLE SET search_path = ''
AS $uid$
  SELECT NULLIF(pg_catalog.current_setting('request.jwt.claim.sub', true), '')::uuid
$uid$;
REVOKE ALL ON FUNCTION auth.uid() FROM PUBLIC;
GRANT USAGE ON SCHEMA auth TO anon, authenticated;
GRANT EXECUTE ON FUNCTION auth.uid() TO anon, authenticated;

CREATE TABLE public.cfo_assets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id),
  title text NOT NULL,
  amount numeric NOT NULL,
  created_at timestamptz DEFAULT now()
);
ALTER TABLE public.cfo_assets ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.cfo_assets
  TO anon, authenticated;
-- Explicit sequence grants are a fixture convenience, not a claim about the
-- real cluster's sequence privileges or Data API access configuration.
GRANT USAGE, SELECT ON SEQUENCE public.cfo_assets_id_seq TO anon, authenticated;
CREATE POLICY fixture_cfo_select ON public.cfo_assets
  FOR SELECT TO PUBLIC USING (auth.uid() = user_id);
CREATE POLICY fixture_cfo_insert ON public.cfo_assets
  FOR INSERT TO PUBLIC WITH CHECK (auth.uid() = user_id);
CREATE POLICY fixture_cfo_delete ON public.cfo_assets
  FOR DELETE TO PUBLIC USING (auth.uid() = user_id);
-- Intentionally no UPDATE policy: table-level UPDATE does not bypass RLS.

